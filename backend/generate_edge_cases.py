templ_idx = 0
for tmpl_text, label_order in standalone_process_templates:
    # 每个模板生成2-3个变体
    for variant in range(2):
        size = random.choice(sizes_list)
        size2 = random.choice(sizes2_list)
        thread = random.choice(threads)
        thread_full = f"M{random.choice(threads)}"
        op = random.choice(ops)
        op2 = random.choice(ops)

        text = tmpl_text.format(
            op=op, op2=op2, size=size, size2=size2,
            thread=thread, M=thread_full, M_thread=thread_full,
        )

        # 为每种实体构建标注
        spans = []
        for label in label_order:
            if label == "工序编号":
                # 找 OPxx 模式
                import re as _re
                for match in _re.finditer(r'OP\d+', text):
                    s, e = match.start(), match.end()
                    # 检查不重叠
                    if all(not (s < e2 and e > s2) for s2, e2, _ in spans):
                        spans.append([s, e, "工序编号"])
            elif label == "工艺":
                process_words = ["钻", "扩", "铰", "镗", "攻丝", "车", "铣", "磨",
                                 "抛光", "珩磨", "回火", "正火", "退火", "淬火"]
                for pw in process_words:
                    pos = text.find(pw)
                    if pos >= 0:
                        pe = pos + len(pw)
                        if all(not (pos < e2 and pe > s2) for s2, e2, _ in spans):
                            spans.append([pos, pe, "工艺"])
                            break
            elif label == "尺寸公差":
                candidates = [size, size2, thread, thread_full,
                              f"Φ{size}", f"Φ{size2}", f"φ{size}", f"φ{size2}",
                              f"M{thread}"]
                for cand in candidates:
                    pos = text.find(cand)
                    if pos >= 0:
                        pe = pos + len(cand)
                        if all(not (pos < e2 and pe > s2) for s2, e2, _ in spans):
                            spans.append([pos, pe, "尺寸公差"])
                            break

        # 如果实体数不够，补一些
        if not spans:
            continue

        samples.append(make_sample(text, spans))
        templ_idx += 1


