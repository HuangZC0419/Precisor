def make_sample(text, spans):
    """spans: list of [start, end, label]"""
    return {
        "text": text,
        "spans": [{"id": i+1, "start": s, "end": e, "label": l}
                   for i, (s, e, l) in enumerate(spans)],
        "relations": [],
        "meta": {},
    }


