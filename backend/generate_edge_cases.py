    tmpl = used_templates[i % len(used_templates)]
    text = tmpl[0].format(size=size)
    spans = []
    # 找尺寸公差的位置
    pos = text.find(size)
    spans.append([pos, pos + len(size), "尺寸公差"])
    # 如果有工艺关键词（如 钻）
    if tmpl[1] == "工艺":
        for kw in ["钻", "加工"]:
            kw_pos = text.find(kw)
            if kw_pos >= 0 and kw_pos != pos:
                # 检查是否与尺寸公差重叠
                kw_end = kw_pos + len(kw)
                if kw_end <= pos or kw_pos >= pos + len(size):
                    spans.append([kw_pos, kw_end, "工艺"])
                    break
    samples.append(make_sample(text, spans))


